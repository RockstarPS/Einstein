#if HM_LANG_MAX_PAGE > 1
  #ifdef HM_LANG_USE_INERNAL_STRING_BUFFER
    /*============================================================================
    ** Function Name:    HmLngGetLanguageString
    ** Visibility:       local
    ** Description:      Reads and updates the string corresponding to passed sid
    **                   in to internal buffer
    ** Invocation:       by hmi_language_if_get_string_ptr
    ** Inputs/Outputs:   in  - sid and language
    **                   out - l_language_string_buffer_A is updated with the string
    ** Critical Section: none
    ** Created:          16-Aug-2010 by EMANOJ1
    ** Updated:          16-Aug-2010 by EMANOJ1
    **==========================================================================*/
    static LANG_SID_T HmLngGetLanguageString(LANG_SID_T p_sid, UINT8 p_language_id_U8)
    {
       UINT8 sidPage = ((p_sid & 0xC000) >> 14);

    #if HM_LANG_MAX_PAGE >= 4
       p_sid = gc_read_language_str[sidPage](p_sid, &l_language_string_buffer_A[0], p_language_id_U8);
    #else
       if(sidPage < HM_LANG_MAX_PAGE)
       {
          p_sid = gc_read_language_str[sidPage](p_sid, &l_language_string_buffer_A[0], p_language_id_U8);
       }
       else
       {
          l_language_string_buffer_A[0] = 0;
          p_sid                         = HM_END_OF_SID;
       }
    #endif
       return(p_sid);
    }
    /*============================================================================
    ** Function Name:    hmi_language_if_get_string_ptr
    ** Visibility:       global
    ** Description:      Returns a pointer to string corresponding to passed sid
    ** Invocation:       by application
    ** Inputs/Outputs:   in - sid to be read, out - pointer to string
    ** Critical Section:
    ** Created:          16-Aug-2010 by EMANOJ1
    ** Updated:          16-Aug-2010 by EMANOJ1
    **==========================================================================*/
    HMI_CHAR * hmi_language_if_get_string_ptr(LANG_SID_T p_sid)
    {
       p_sid = HmLngGetLanguageString(p_sid, l_current_language_id_U8);

       if(p_sid != HM_END_OF_SID)
       {
       #ifdef WIN32
          if(HmLngGetLanguageString(p_sid, 0) != HM_END_OF_SID)
          {
             printf("Error in Encode!!! SID(%04X) linking > 1 Level\n", p_sid);
          }
       #else
          (void)HmLngGetLanguageString(p_sid, 0);
       #endif
       }
       return(&l_language_string_buffer_A[0]);
    }
  #else /* ! HM_LANG_USE_INERNAL_STRING_BUFFER */
    /*============================================================================
    ** Function Name:    HmLngGetLanguageString
    ** Visibility:       local
    ** Description:      Reads and updates the string corresponding to passed sid
    **                   in to passed buffer
    ** Invocation:       by hmi_language_if_get_string_ptr
    ** Inputs/Outputs:   in  - sid and language
    **                   out - p_string_buff_P is updated with the string
    ** Critical Section: none
    ** Created:          16-Aug-2010 by EMANOJ1
    ** Updated:          16-Aug-2010 by EMANOJ1
    **==========================================================================*/
    static LANG_SID_T HmLngGetLanguageString(LANG_SID_T p_sid, UINT8 p_language_id_U8, HMI_CHAR * p_string_buff_P, UINT8 p_req_length)
    {
       UINT8 sidPage = ((p_sid & 0xC000) >> 14);

    #if HM_LANG_MAX_PAGE >= 4
       p_sid = gc_read_language_str[sidPage](p_sid, p_string_buff_P, p_req_length, p_language_id_U8);
    #else
       if(sidPage < HM_LANG_MAX_PAGE)
       {
          p_sid = gc_read_language_str[sidPage](p_sid, p_string_buff_P, p_req_length, p_language_id_U8);
       }
       else
       {
          p_string_buff_P[0] = 0;
          p_sid = HM_END_OF_SID;
       }
    #endif
       return(p_sid);
    }
    /*============================================================================
    ** Function Name:    hmi_language_if_get_string_ptr
    ** Visibility:       local
    ** Description:      Updates string corresponding to the passed sid
    ** Invocation:       by application
    ** Inputs/Outputs:   in  - sid, string buffer, buffer length
    **                   out - string buffer is updated with the string
    ** Critical Section: none
    ** Created:          16-Aug-2010 by EMANOJ1
    ** Updated:          16-Aug-2010 by EMANOJ1
    **==========================================================================*/
    void hmi_language_if_get_string_ptr(LANG_SID_T p_sid, HMI_CHAR * p_string_buff_P, UINT8 p_req_length)
    {
       if((p_string_buff_P != NULL) && (p_req_length > 0))
       {
          p_sid = HmLngGetLanguageString(p_sid, l_current_language_id_U8, p_string_buff_P, p_req_length);

          if(p_sid != HM_END_OF_SID)
          {
          #ifdef WIN32
             if(HmLngGetLanguageString(p_sid, 0, p_string_buff_P, p_req_length) != HM_END_OF_SID)
             {
                printf("Error in Encode!!! SID(%04X) linking > 1 Level\n", p_sid);
             }
          #else
             (void)HmLngGetLanguageString(p_sid, 0, p_string_buff_P, p_req_length);
          #endif
          }
       }
    }
  #endif
#else /* #if HM_LANG_MAX_PAGE == 1 */
  #ifdef HM_LANG_USE_INERNAL_STRING_BUFFER
    /*============================================================================
    ** Function Name:    hmi_language_if_get_string_ptr
    ** Visibility:       local
    ** Description:      Returns pointer to string corresponding to the passed sid
    ** Invocation:       by hmi_language_if_get_string_ptr
    ** Inputs/Outputs:   in  - sid
    **                   out - l_language_string_buffer_A is updated with the string
    ** Critical Section: none
    ** Created:          16-Aug-2010 by EMANOJ1
    ** Updated:          16-Aug-2010 by EMANOJ1
    **==========================================================================*/
    HMI_CHAR * hmi_language_if_get_string_ptr(LANG_SID_T p_sid)
    {
       p_sid = HmLanguage1GetString(p_sid, &l_language_string_buffer_A[0], l_current_language_id_U8);

       if(p_sid != HM_END_OF_SID)
       {
       #ifdef WIN32
          if(HmLanguage1GetString(p_sid, &l_language_string_buffer_A[0], 0) != HM_END_OF_SID)
          {
             printf("Error in Encode!!! SID(%04X) linking > 1 Level\n", p_sid);
          }
       #else
          (void)HmLanguage1GetString(p_sid, &l_language_string_buffer_A[0], 0);
       #endif
       }
       return(&l_language_string_buffer_A[0]);
    }
  #else
    /*============================================================================
    ** Function Name:    hmi_language_if_get_string_ptr
    ** Visibility:       local
    ** Description:      Returns pointer to string corresponding to the passed sid
    ** Invocation:       by hmi_language_if_get_string_ptr
    ** Inputs/Outputs:   in  - sid, pointer to a string buffer and its length
    **                   out - passed buffer is updated with the string
    ** Critical Section: none
    ** Created:          16-Aug-2010 by EMANOJ1
    ** Updated:          16-Aug-2010 by EMANOJ1
    **==========================================================================*/
    void hmi_language_if_get_string_ptr(LANG_SID_T p_sid, HMI_CHAR * p_string_buff_P, UINT8 p_req_length )
    {
       if((p_string_buff_P != NULL) && (p_req_length > (UINT8)0))
       {
          LANG_SID_T fl_sid = HmLanguage1GetString(p_sid, p_string_buff_P, p_req_length, l_current_language_id_U8);

          if(fl_sid != HM_END_OF_SID)
          {
          #ifdef WIN32
             if(HmLanguage1GetString(fl_sid, p_string_buff_P, p_req_length, 0) != HM_END_OF_SID)
             {
                printf("Error in Encode!!! SID(%04X) linking > 1 Level\n", fl_sid);
             }
          #else
             (void)HmLanguage1GetString(fl_sid, p_string_buff_P, p_req_length, 0);
          #endif
          }
       }
    }
  #endif
#endif

