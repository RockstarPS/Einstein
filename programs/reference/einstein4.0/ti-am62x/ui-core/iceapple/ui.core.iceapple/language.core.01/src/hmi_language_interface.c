UINT32 hmi_language_strlen_u32(const UINT32 *p_string)
{
  const UINT32 *sc;
  SINT32 result;
  for (sc = p_string; *sc != (UINT32)'\0'; ++sc)
  {
    /* nothing */;
  }
  result = sc - p_string;
  return (UINT32)result;
}

SINT32 hmi_language_strcmp_u32(const UINT32 *p_string1, const UINT32 *p_string2)
{
  SINT32 fl_return = 0;
  UINT32 c1, c2;
  const UINT32 *fl_string1 = p_string1;
  const UINT32 *fl_string2 = p_string2;
  while((BOOLEAN)1)
  {
    c1 = *fl_string1;
    c2 = *fl_string2;
    if (c1 != c2)
    {
      fl_return = ((c1 < c2) ? -1 : 1);
      break;
    }
    if (c1 == 0U)
    {
      break;
    }
    fl_string1++;
    fl_string2++;
  }
  return fl_return;
}

UINT32* hmi_language_strcpy_u32(UINT32 *p_dest, const UINT32 *p_src)
{
  UINT32 *fl_return = p_dest;
  UINT32 *fl_dest = p_dest;
  const UINT32* fl_src = p_src;
  while ((BOOLEAN)1)
  {
    *fl_dest = *fl_src;
    if(*fl_src == (UINT32)'\0')
    {
      break;
    }
    fl_src++;
    fl_dest++;
  }
  return fl_return;
}

UINT32* hmi_language_strncpy_u32(UINT32 *p_dest, const UINT32 *p_src, UINT32 p_count)
{
  UINT32 *fl_return = p_dest;
  UINT32 *fl_dest = p_dest;
  const UINT32 *fl_src = p_src;
  UINT32 fl_count = p_count;
  while (fl_count != 0U) 
  {
    *fl_dest = *fl_src;
    if (*fl_dest != 0)
    {
      fl_src++;
    }
    fl_dest++;
    fl_count--;
  }
  return fl_return;
}



