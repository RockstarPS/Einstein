/*============================================================================
** Function Name:    hmi_language_get_wide_char
** Visibility:       global
** Description:      Wide conversion function. Use if the compiler doesn't support
**                   L conversion of ASCII strings.
** Invocation:       When ever needed as GFX_TEXT("ascii string").
** Inputs/Outputs:   None.
** Critical Section: None.
** Created:          03-Mar-2010 by EMANOJ1
** Created:          03-Mar-2010 by EMANOJ1
**==========================================================================*/
HMI_CHAR * hmi_language_get_wide_char(UINT8 const * p_ascii_str_ptr)
{
  static HMI_CHAR l_gfx_if_unicode_str[HMI_LANG_MAX_L_TEXT_LENGTH];
  UINT16 fl_index_U16  = 0;

  const UINT8 * fl_ascii_str_ptr = p_ascii_str_ptr;
  while((fl_index_U16 < ((UINT16)(((UINT16)HMI_LANG_MAX_L_TEXT_LENGTH)-((UINT16)1)))) && (*fl_ascii_str_ptr != (UINT8)0))
  {
    l_gfx_if_unicode_str[fl_index_U16] = (wchar_t)(*fl_ascii_str_ptr);
    fl_ascii_str_ptr = &fl_ascii_str_ptr[1];
    fl_index_U16++;
  }
  l_gfx_if_unicode_str[fl_index_U16] = (wchar_t)(0);

  return(&l_gfx_if_unicode_str[0]);
}
#endif


